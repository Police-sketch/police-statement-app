import streamlit as st
import openai  # Or google.generativeai if using Gemini API

# Initialize Streamlit Page Config
st.set_page_config(page_title="Smart Police Statement Generator", layout="centered")

st.title("🛡️ Automated Police Statement Intake Assistant")
st.markdown("This system helps citizens record incidents step-by-step through a guided interview and automatically generates a formal police statement.")

# Initialize session state for conversation history and incident data
if "messages" not in st.session_state:
    st.session_state.messages = [
        {"role": "system", "content": "You are a professional, empathetic, and objective police intake officer. Your job is to interview a citizen reporting an incident. Ask clear, concise questions one at a time to gather all necessary details: Who, What, When, Where, Why, and How. Do not generate the final statement until the user indicates they have finished providing details."}
    ]

if "interview_complete" not in st.session_state:
    st.session_state.interview_complete = False

# Display chat history
for message in st.session_state.messages:
    if message["role"] != "system":
        with st.chat_message(message["role"]):
            st.markdown(message["content"])

# User Input for Interview
if not st.session_state.interview_complete:
    user_input = st.chat_input("Type your response here (e.g., 'My car was broken into last night...')")
    
    if user_input:
        # Append user message
        st.session_state.messages.append({"role": "user", "content": user_input})
        with st.chat_message("user"):
            st.markdown(user_input)
            
        # Simulate or call LLM API for the AI response
        # Note: Replace this block with your actual API call (e.g., OpenAI or Gemini API)
        prompt_history = st.session_state.messages
        
        # Placeholder response logic representing the AI agent guiding the interview
        ai_response = "Thank you for sharing that. Could you tell me approximately what time this occurred, and whether you noticed any identifying marks or items left behind?"
        
        st.session_state.messages.append({"role": "assistant", "content": ai_response})
        with st.chat_message("assistant"):
            st.markdown(ai_response)
            
        # Button to finish and generate report
        if st.button("Finish Interview & Generate Statement"):
            st.session_state.interview_complete = True
            st.rerun()

# Generate Formal Police Statement once interview is complete
if st.session_state.interview_complete:
    st.success("Interview concluded. Generating formal police statement...")
    
    # Compile conversation into a formal layout
    formal_statement = """
    ==================================================
              OFFICIAL POLICE STATEMENT REPORT
    ==================================================
    Date of Report: 2026-10-22
    Station Ref: INT-2026-9942
    
    [INCIDENT NARRATIVE SUMMARY GENERATED BY AI]
    The reporting party stated that an incident occurred... 
    (Generated dynamically from full chat transcript analysis).
    
    Declaration: I certify that the above statement is true 
    and correct to the best of my knowledge.
    
    Signature: ______________________
    ==================================================
    """
    
    st.text_area("Final Formatted Statement:", formal_statement, height=250)
    st.download_button("Download Statement as PDF/TXT", formal_statement, file_name="Police_Statement.txt")
